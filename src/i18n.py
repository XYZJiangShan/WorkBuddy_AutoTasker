def set_language(lang: str) -> None:
    global _current_lang
    _current_lang = lang if lang in _TEXTS else _DEFAULT_LANG


def get_language() -> str:
    return _current_lang


def t(key: str, **kwargs: Any) -> str:
    text = _TEXTS.get(_current_lang, _TEXTS[_DEFAULT_LANG]).get(key)
    if text is None:
        text = _TEXTS[_DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
